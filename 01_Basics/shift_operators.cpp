#include<iostream>
using namespace std;
int main()
{
    int n = 8;
    //left shift (multiply by 2 ) 
    cout<<"n << 1: "<<(n << 1)<<endl;
    cout<<"n <<2: "<<(n << 2)<<endl;
    //right shift(divide by 2)
    cout<<"n >> 1: "<<(n >> 1)<<endl;
    cout<<"n >> 2: "<<(n >> 2)<<endl;
    return 0;

}
